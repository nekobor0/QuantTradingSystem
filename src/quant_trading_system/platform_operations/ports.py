from datetime import date, datetime
from typing import Mapping, Protocol
from uuid import UUID
from .domain import *

class OperationsRepository(Protocol):
    def latest_task(self, task_type:TaskType, business_date:date, input_hash:str|None=None)->TaskRun|None: ...
    def get_task(self, task_run_id:UUID)->TaskRun|None: ...
    def save_task(self, task:TaskRun)->None: ...
    def replace_task(self, task:TaskRun, expected_fencing_token:int)->None: ...
    def save_task_and_event(self, task:TaskRun, event:OutboxEvent, expected_fencing_token:int)->None: ...
    def pending_events(self)->tuple[OutboxEvent,...]: ...
    def replace_event(self, event:OutboxEvent)->None: ...
    def checkpoint(self, consumer:str, event_id:UUID)->ConsumerCheckpoint|None: ...
    def save_checkpoint(self, value:ConsumerCheckpoint)->None: ...
    def save_batch(self, value:DatasetBatch)->None: ...
    def latest_batch(self, dataset:str)->DatasetBatch|None: ...
    def save_configuration(self, value:ConfigurationVersion)->None: ...
    def active_configuration(self, environment:str, as_of:datetime)->ConfigurationVersion|None: ...
    def save_backup(self, value:BackupRecord)->None: ...
    def latest_backup(self)->BackupRecord|None: ...
    def save_alert(self, value:AlertRecord)->None: ...
    def save_audit(self, value:OperationalAudit)->None: ...

class TaskHandler(Protocol):
    def execute(self, task:TaskRun)->Mapping[str,str]: ...
class EventTransport(Protocol):
    def publish(self, event:OutboxEvent)->None: ...
class HealthProbe(Protocol):
    def database_ok(self)->bool: ...
    def account_reconciled(self, business_date:date)->bool: ...
    def risk_succeeded(self, business_date:date)->bool: ...
class AlertSink(Protocol):
    def send(self, category:str, message:str, correlation_id:str)->bool: ...
