from typing import Protocol,Sequence
from uuid import UUID
from .domain import *
class UniverseRepository(Protocol):
 def save_definition(self,value:UniverseDefinition)->None:...
 def get_definition(self,universe_id:UUID)->UniverseDefinition|None:...
 def list_definitions(self)->Sequence[UniverseDefinition]:...
 def get_batch(self,universe_id:UUID,source_batch_id:str)->MembershipBatch|None:...
 def active_periods_before(self,universe_id:UUID,effective_date:object)->Sequence[MembershipPeriod]:...
 def apply_batch(self,batch:MembershipBatch,closed:Sequence[MembershipPeriod],opened:Sequence[MembershipPeriod],event:UniverseMembershipChanged)->None:...
 def reject_batch(self,batch:MembershipBatch,results:Sequence[UniverseQualityResult])->None:...
 def periods(self,universe_id:UUID)->Sequence[MembershipPeriod]:...
 def batches(self,universe_id:UUID)->Sequence[MembershipBatch]:...
 def save_snapshot(self,value:UniverseSnapshot)->None:...
 def get_snapshot(self,snapshot_id:UUID)->UniverseSnapshot|None:...
 def save_classification(self,value:ClassificationMembership)->None:...
 def classifications(self,instrument_id:UUID)->Sequence[ClassificationMembership]:...
 def quality_results(self,batch_id:UUID)->Sequence[UniverseQualityResult]:...
