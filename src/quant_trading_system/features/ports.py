from typing import Protocol,Sequence
from uuid import UUID
from .domain import *
class FeatureRepository(Protocol):
 def save_definition(self,d:FeatureDefinition,versions:Sequence[FeatureVersion])->None:...
 def get_definition(self,i:UUID)->FeatureDefinition|None:...
 def get_version(self,i:UUID)->FeatureVersion|None:...
 def bind(self,purpose:FeaturePurpose,version_ids:Sequence[UUID])->None:...
 def binding(self,purpose:FeaturePurpose)->Sequence[UUID]:...
 def find_set(self,input_hash:str)->FeatureSet|None:...
 def save_set(self,s:FeatureSet,values:Sequence[FeatureValue],event:FeatureEvent)->None:...
 def get_set(self,i:UUID)->FeatureSet|None:...
 def values(self,i:UUID)->Sequence[FeatureValue]:...
 def save_rejected_event(self,event:FeatureEvent)->None:...
 def latest_event(self)->FeatureEvent|None:...
