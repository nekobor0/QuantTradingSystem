from typing import Protocol,Sequence
from uuid import UUID
from .domain import *
class LedgerRepository(Protocol):
 def save_account(self,a:Account)->None:...
 def get_account(self,i:UUID)->Account|None:...
 def update_account(self,a:Account)->None:...
 def find_order(self,account_id:UUID,key:str)->Order|None:...
 def get_order(self,i:UUID)->Order|None:...
 def save_order(self,o:Order,event:LedgerEvent)->None:...
 def update_order(self,o:Order,event:LedgerEvent)->None:...
 def find_fill(self,broker:str,account_id:UUID,key:str)->Fill|None:...
 def get_fill(self,i:UUID)->Fill|None:...
 def reversal_for(self,i:UUID)->Fill|None:...
 def record_fill(self,fill:Fill,entries:Sequence[LedgerEntry],order:Order,event:LedgerEvent)->None:...
 def entries(self,account_id:UUID)->Sequence[LedgerEntry]:...
 def find_cash_event(self,account_id:UUID,external_ref:str)->CashEvent|None:...
 def record_cash(self,event_value:CashEvent,entry:LedgerEntry,event:LedgerEvent)->None:...
 def save_snapshot(self,s:AccountSnapshot)->None:...
 def save_reconciliation(self,r:Reconciliation,a:Account,event:LedgerEvent)->None:...
 def get_reconciliation(self,i:UUID)->Reconciliation|None:...
 def save_import(self,i:StatementImport)->None:...
 def find_import(self,account_id:UUID,file_hash:str,format_version:str)->StatementImport|None:...
 def get_import(self,import_id:UUID)->StatementImport|None:...
 def latest_event(self)->LedgerEvent|None:...
