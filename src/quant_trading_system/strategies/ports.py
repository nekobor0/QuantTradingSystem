from typing import Protocol,Sequence
from uuid import UUID
from .domain import *
class StrategyRepository(Protocol):
 def save_definition(self,d:StrategyDefinition,versions:Sequence[StrategyVersion])->None:...
 def get_definition(self,i:UUID)->StrategyDefinition|None:...
 def get_version(self,i:UUID)->StrategyVersion|None:...
 def find_run(self,input_hash:str)->StrategyRun|None:...
 def active_run(self,kind:StrategyKind,decision_at:object)->StrategyRun|None:...
 def save_result(self,result:StrategyResult,event:StrategyEvent)->None:...
 def save_failed(self,run:StrategyRun,event:StrategyEvent)->None:...
 def get_result(self,i:UUID)->StrategyResult|None:...
 def save_evidence(self,e:ResearchEvidence)->None:...
 def evidence(self,version_id:UUID)->Sequence[ResearchEvidence]:...
 def latest_event(self)->StrategyEvent|None:...
