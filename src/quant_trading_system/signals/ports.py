from typing import Protocol,Sequence
from uuid import UUID
from .domain import *
class SignalRepository(Protocol):
 def find(self,input_hash:str)->Signal|None:...
 def save_draft(self,result:SignalResult,event:SignalEvent)->None:...
 def update_signal(self,signal:Signal,event:SignalEvent)->None:...
 def get_result(self,signal_id:UUID)->SignalResult|None:...
 def get_recommendation(self,i:UUID)->Recommendation|None:...
 def apply_approval(self,recommendation:Recommendation,approval:ApprovalDecision,event:SignalEvent)->None:...
 def get_approval(self,decision_id:UUID)->ApprovalDecision|None:...
 def save_supersession(self,value:SignalSupersession,old:Signal,new:Signal,event:SignalEvent)->None:...
 def all_results(self)->Sequence[SignalResult]:...
 def latest_event(self)->SignalEvent|None:...
