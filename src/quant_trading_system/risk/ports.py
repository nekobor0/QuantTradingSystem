from typing import Protocol,Sequence
from uuid import UUID
from .domain import *
class RiskRepository(Protocol):
 def save_rule(self,rule:RiskRule)->None:...
 def save_rule_version(self,version:RiskRuleVersion)->None:...
 def get_rule_version(self,version_id:UUID)->RiskRuleVersion|None:...
 def save_policy(self,policy:RiskPolicyVersion)->None:...
 def get_policy(self,policy_version_id:UUID)->RiskPolicyVersion|None:...
 def find_run(self,input_hash:str)->RiskCheckRun|None:...
 def save_run_result(self,value:RiskRunResult,alerts:Sequence[RiskAlert],event:RiskEvent)->None:...
 def get_run_result(self,run_id:UUID)->RiskRunResult|None:...
 def get_result(self,result_id:UUID)->RiskCheckResult|None:...
 def save_exception(self,value:RiskException,event:RiskEvent)->None:...
 def get_exception(self,exception_id:UUID)->RiskException|None:...
 def exceptions_for(self,result_id:UUID)->Sequence[RiskException]:...
 def get_alert(self,alert_id:UUID)->RiskAlert|None:...
 def find_alert(self,dedupe_key:str)->RiskAlert|None:...
 def update_alert(self,value:RiskAlert,event:RiskEvent)->None:...
 def alerts_for_account(self,account_id:UUID)->Sequence[RiskAlert]:...
 def runs_for_account(self,account_id:UUID)->Sequence[RiskCheckRun]:...
 def runs_for_target(self,target_id:UUID)->Sequence[RiskRunResult]:...
