from typing import Protocol
from uuid import UUID

from .domain import BacktestDefinition, BacktestResult, BacktestRun


class BacktestRepository(Protocol):
    def find_run(self, input_hash: str) -> BacktestRun | None: ...
    def save_started(self, definition: BacktestDefinition, run: BacktestRun) -> None: ...
    def save_result(self, result: BacktestResult) -> None: ...
    def save_failed(self, run: BacktestRun) -> None: ...
    def get_result(self, run_id: UUID) -> BacktestResult | None: ...

