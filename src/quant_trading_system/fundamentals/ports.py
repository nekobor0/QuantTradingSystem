from typing import Protocol, Sequence
from uuid import UUID
from .domain import *
class FundamentalRepository(Protocol):
    def save_definition(self, metric: MetricDefinition, mappings: Sequence[SourceMapping]) -> None: ...
    def get_mapping(self, source: str, field: str) -> SourceMapping|None: ...
    def get_metric(self, metric_id: UUID) -> MetricDefinition|None: ...
    def find_filing(self, source: str, source_filing_id: str, revision: str) -> Filing|None: ...
    def filing_revisions(self, source: str, source_filing_id: str) -> Sequence[Filing]: ...
    def save_rejected(self, filing: Filing|None, identity: tuple[str,str,str], results: Sequence[QualityResult]) -> None: ...
    def publish(self, filing: Filing, facts: Sequence[FundamentalFact], event: FundamentalRevisionEvent) -> None: ...
    def published_facts(self) -> Sequence[tuple[FundamentalFact,Filing]]: ...
    def quality_results(self, identity: tuple[str,str,str]) -> Sequence[QualityResult]: ...
    def latest_event(self) -> FundamentalRevisionEvent | None: ...
    def save_share_change(self, change: ShareCapitalChange) -> None: ...
    def share_changes(self, instrument_id: UUID) -> Sequence[ShareCapitalChange]: ...
